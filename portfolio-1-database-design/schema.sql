-- =====================================================================
-- TosiPay - Mobile Wallet & Agent Banking Platform
-- Portfolio 1: Relational schema (PostgreSQL 16+)
--
-- Run:  psql -U postgres -d tosipay -f schema.sql
-- The script is re-runnable: it drops and recreates the tosipay schema.
-- =====================================================================

DROP SCHEMA IF EXISTS tosipay CASCADE;
CREATE SCHEMA tosipay;
SET search_path TO tosipay;

-- ---------------------------------------------------------------------
-- 1. KYC tiers (reference data, modelled on CBN tiered KYC).
--    The tier is held per customer and applies to all of their accounts.
--    The identity documents each tier needs are enforced on customer.
-- ---------------------------------------------------------------------
CREATE TABLE kyc_tier (
    kyc_tier_id         SMALLINT      PRIMARY KEY,
    tier_name           VARCHAR(20)   NOT NULL UNIQUE,
    daily_txn_limit     NUMERIC(18,2) NOT NULL CHECK (daily_txn_limit > 0),
    max_balance         NUMERIC(18,2)          CHECK (max_balance > 0) -- NULL = no cap
);

-- ---------------------------------------------------------------------
-- 2. Customers (wallet holders)
-- ---------------------------------------------------------------------
CREATE TABLE customer (
    customer_id     INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(50)   NOT NULL,
    last_name       VARCHAR(50)   NOT NULL,
    phone_number    VARCHAR(14)   NOT NULL UNIQUE
                    CHECK (phone_number ~ '^\+234[0-9]{10}$'),
    email           VARCHAR(120)  UNIQUE
                    CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    bvn             CHAR(11)      UNIQUE
                    CHECK (bvn ~ '^[0-9]{11}$'),
    nin             CHAR(11)      UNIQUE
                    CHECK (nin ~ '^[0-9]{11}$'),
    date_of_birth   DATE          NOT NULL CHECK (date_of_birth > DATE '1900-01-01'),
    kyc_tier_id     SMALLINT      NOT NULL DEFAULT 1 REFERENCES kyc_tier (kyc_tier_id),
    status          VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Business rule: Tier 1 needs at least one of BVN / NIN;
    -- Tier 2 and above need both.
    CONSTRAINT chk_customer_kyc_ids CHECK (
           (kyc_tier_id = 1 AND (bvn IS NOT NULL OR nin IS NOT NULL))
        OR (bvn IS NOT NULL AND nin IS NOT NULL)
    )
);

-- ---------------------------------------------------------------------
-- 3. Agents (POS / cash-in cash-out points). Every agent business is run
--    by a registered customer, so a person's personal accounts and their
--    agent float account can be traced back to the same customer_id.
-- ---------------------------------------------------------------------
CREATE TABLE agent (
    agent_id            INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_customer_id   INTEGER       NOT NULL REFERENCES customer (customer_id),
    business_name       VARCHAR(100)  NOT NULL,
    phone_number        VARCHAR(14)   NOT NULL UNIQUE
                        CHECK (phone_number ~ '^\+234[0-9]{10}$'),
    state               VARCHAR(30)   NOT NULL,
    lga                 VARCHAR(50)   NOT NULL,
    status              VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    onboarded_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 4. Account types (reference data). owner_kind states who may hold an
--    account of this type: a customer, an agent, or TosiPay itself.
-- ---------------------------------------------------------------------
CREATE TABLE account_type (
    account_type_code   VARCHAR(15)   PRIMARY KEY,
    type_name           VARCHAR(40)   NOT NULL UNIQUE,
    owner_kind          VARCHAR(8)    NOT NULL
                        CHECK (owner_kind IN ('CUSTOMER', 'AGENT', 'SYSTEM')),
    interest_rate_pa    NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (interest_rate_pa >= 0),
    min_balance         NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (min_balance >= 0),
    -- Target of the composite foreign key from account (see below).
    UNIQUE (account_type_code, owner_kind)
);

-- ---------------------------------------------------------------------
-- 5. Accounts. An account belongs to exactly one customer, OR exactly
--    one agent, OR to TosiPay itself (SYSTEM accounts such as the bank
--    settlement account and fee income account).
--
--    owner_kind is copied from account_type and kept correct by the
--    composite foreign key, which lets a CHECK constraint enforce that
--    the owner columns match the type (a CHECK cannot read another table).
-- ---------------------------------------------------------------------
CREATE TABLE account (
    account_id          INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number      CHAR(10)      NOT NULL UNIQUE CHECK (account_number ~ '^[0-9]{10}$'),
    account_type_code   VARCHAR(15)   NOT NULL,
    owner_kind          VARCHAR(8)    NOT NULL,
    customer_id         INTEGER       REFERENCES customer (customer_id),
    agent_id            INTEGER       REFERENCES agent (agent_id),
    currency            CHAR(3)       NOT NULL DEFAULT 'NGN',
    balance             NUMERIC(18,2) NOT NULL DEFAULT 0,
    status              VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    opened_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_account_type FOREIGN KEY (account_type_code, owner_kind)
        REFERENCES account_type (account_type_code, owner_kind),
    -- Ownership must match the account type's owner_kind.
    CONSTRAINT chk_account_owner CHECK (
           (owner_kind = 'CUSTOMER' AND customer_id IS NOT NULL AND agent_id IS NULL)
        OR (owner_kind = 'AGENT'    AND agent_id IS NOT NULL    AND customer_id IS NULL)
        OR (owner_kind = 'SYSTEM'   AND customer_id IS NULL     AND agent_id IS NULL)
    ),
    -- Customer/agent accounts can never be overdrawn. The settlement
    -- (SYSTEM) account mirrors money held at the partner bank and may go negative.
    -- (Per-type min_balance is enforced by the posting logic in Portfolio 3.)
    CONSTRAINT chk_account_non_negative CHECK (balance >= 0 OR owner_kind = 'SYSTEM')
);

-- ---------------------------------------------------------------------
-- 6. Transactions (the instruction / header). One row per attempt,
--    including FAILED attempts, which never produce ledger entries.
-- ---------------------------------------------------------------------
CREATE TABLE txn (
    txn_id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference               VARCHAR(30)   NOT NULL UNIQUE,  -- idempotency key from the app
    txn_type                VARCHAR(15)   NOT NULL
                            CHECK (txn_type IN ('FLOAT_TOPUP', 'DEPOSIT', 'WITHDRAWAL',
                                                'TRANSFER', 'BILL_PAYMENT', 'REVERSAL')),
    channel                 VARCHAR(10)   NOT NULL
                            CHECK (channel IN ('APP', 'USSD', 'AGENT_POS', 'SYSTEM')),
    source_account_id       INTEGER       NOT NULL REFERENCES account (account_id),
    destination_account_id  INTEGER       REFERENCES account (account_id), -- NULL for bill payments
    amount                  NUMERIC(18,2) NOT NULL CHECK (amount > 0),
    fee                     NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (fee >= 0),
    status                  VARCHAR(10)   NOT NULL DEFAULT 'PENDING'
                            CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REVERSED')),
    failure_reason          VARCHAR(200),
    reverses_txn_id         BIGINT        UNIQUE REFERENCES txn (txn_id), -- a txn can be reversed once
    narration               VARCHAR(140),
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    completed_at            TIMESTAMPTZ,

    CONSTRAINT chk_txn_distinct_accounts CHECK (source_account_id <> destination_account_id),
    CONSTRAINT chk_txn_reversal_link     CHECK ((txn_type = 'REVERSAL') = (reverses_txn_id IS NOT NULL)),
    CONSTRAINT chk_txn_failure_reason    CHECK ((status = 'FAILED') = (failure_reason IS NOT NULL)),
    CONSTRAINT chk_txn_completed_time    CHECK (completed_at IS NULL OR completed_at >= created_at)
);

-- ---------------------------------------------------------------------
-- 7. Bill payment details (1:1 subtype of txn for BILL_PAYMENT rows)
-- ---------------------------------------------------------------------
CREATE TABLE biller (
    biller_id       SMALLINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biller_name     VARCHAR(80)   NOT NULL UNIQUE,
    category        VARCHAR(20)   NOT NULL
                    CHECK (category IN ('ELECTRICITY', 'AIRTIME', 'DATA', 'CABLE_TV', 'WATER'))
);

CREATE TABLE bill_payment (
    txn_id              BIGINT       PRIMARY KEY REFERENCES txn (txn_id),
    biller_id           SMALLINT     NOT NULL REFERENCES biller (biller_id),
    customer_reference  VARCHAR(30)  NOT NULL,  -- meter no., smartcard no., phone no.
    token               VARCHAR(40)             -- e.g. prepaid electricity token
);

-- ---------------------------------------------------------------------
-- 8. Ledger (double-entry postings). Every successful txn produces
--    balanced DEBIT and CREDIT entries; this is the source of truth for money.
-- ---------------------------------------------------------------------
CREATE TABLE ledger_entry (
    entry_id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id          BIGINT        NOT NULL REFERENCES txn (txn_id),
    account_id      INTEGER       NOT NULL REFERENCES account (account_id),
    entry_type      CHAR(6)       NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount          NUMERIC(18,2) NOT NULL CHECK (amount > 0),
    balance_after   NUMERIC(18,2) NOT NULL,
    posted_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Debits must equal credits for every transaction. This cannot be a
-- CHECK constraint (it spans rows), so it is a DEFERRED constraint
-- trigger: it is evaluated at COMMIT, after all entries are inserted.
CREATE FUNCTION check_txn_balanced() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_debits  NUMERIC(18,2);
    v_credits NUMERIC(18,2);
BEGIN
    SELECT COALESCE(SUM(amount) FILTER (WHERE entry_type = 'DEBIT'),  0),
           COALESCE(SUM(amount) FILTER (WHERE entry_type = 'CREDIT'), 0)
      INTO v_debits, v_credits
      FROM ledger_entry
     WHERE txn_id = NEW.txn_id;

    IF v_debits <> v_credits THEN
        RAISE EXCEPTION 'Transaction % is unbalanced: debits % <> credits %',
                        NEW.txn_id, v_debits, v_credits;
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_ledger_balanced
    AFTER INSERT OR UPDATE ON ledger_entry
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_txn_balanced();

-- ---------------------------------------------------------------------
-- 9. Audit log: every change to an account (balance, status) is recorded.
-- ---------------------------------------------------------------------
CREATE TABLE audit_log (
    audit_id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name      VARCHAR(40)   NOT NULL,
    record_id       BIGINT        NOT NULL,
    action          VARCHAR(6)    NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_data        JSONB,
    new_data        JSONB,
    changed_by      VARCHAR(63)   NOT NULL DEFAULT current_user,
    changed_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE FUNCTION audit_account_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO audit_log (table_name, record_id, action, old_data, new_data)
    VALUES ('account', NEW.account_id, TG_OP,
            CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(OLD) END,
            to_jsonb(NEW));
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_audit_account
    AFTER INSERT OR UPDATE ON account
    FOR EACH ROW EXECUTE FUNCTION audit_account_change();

-- Note: only the indexes created automatically by PRIMARY KEY and UNIQUE
-- constraints exist at this stage. Secondary indexes (e.g. on foreign keys
-- such as ledger_entry.account_id) are added and measured in Portfolio 2.
